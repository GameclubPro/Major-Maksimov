const settingsKeys = Object.keys(CHAT_SETTINGS_SQL_COLUMNS) as (keyof ChatSettings)[];

export type ChatSettingsProjection = {
  [K in keyof ChatSettings as `settings_${K}`]: ChatSettings[K] | null;
};

// FLAG: Identifiers come only from the static exhaustive map. Alias the camelCase key:
// prefixing the longest physical column would exceed PostgreSQL's 63-byte identifier limit.
export const CHAT_SETTINGS_SQL_PROJECTION = Prisma.join(
  settingsKeys.map((key) =>
    Prisma.raw(`s."${CHAT_SETTINGS_SQL_COLUMNS[key]}" AS "settings_${key}"`),
  ),
);

export function readProjectedChatSettings(row: ChatSettingsProjection): ChatSettings | null {
  if (row.settings_id === null) return null;
  // FLAG: The exhaustive projection preserves native driver values without JSON conversion.
  return Object.fromEntries(
    settingsKeys.map((key) => [key, row[`settings_${key}`]]),
  ) as ChatSettings;
}
